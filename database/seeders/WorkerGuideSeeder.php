    public function run(): void
    {
        foreach ($this->guides() as $data) {
            $sections = $data['sections'];
            unset($data['sections']);

            $guide = WorkerGuide::query()->firstOrNew(['key' => $data['key']]);

            // 노출 여부만 보존한다 — 운영에서 내려 둔 자료가 다시 켜지면 안 된다.
            // 나머지는 원본 문서가 원본이므로 시더 값으로 맞춘다.
            if ($guide->exists) {
                unset($data['active']);
            }
            $guide->fill($data)->save();

            // 본문은 원본 문서가 원본이므로 통째로 다시 깐다.
            $guide->sections()->delete();
            foreach ($sections as $i => $section) {
                $guide->sections()->create([
                    'type' => $section['type'],
                    'position' => $i + 1,
                    'payload' => $section['payload'],
                ]);
            }
        }
    }

